"""Every figure in the report, drawn from the artifact store and nothing else.

Build spec 20: every figure and table is a file generated by the pipeline. This script is
the generator for the figures. It reads the ingest, grid, and audit stage artifacts for the
current config hash and writes vector PDFs into ``report/figures/``.

It reads no CSV from outside the repository and computes no headline statistic that a stage
has not already recorded. Where a figure needs a derived quantity for its own annotation (a
Pearson correlation on a scatter, a pointwise percentile band), it computes it from the
artifact it is plotting and writes it to ``figure_stats.json`` beside this file, so even the
annotations are traceable.

Style comes from :mod:`ufem.plotting.style`, the single style module of build spec section 8.
The two figures the audit phase adds, the completion probability surface and the calibration
reliability diagram, are drawn by :mod:`ufem.plotting.censoring`.

Deterministic: no random number generation anywhere, and the PDF creation timestamp is pinned
by the style module, so rerunning on unchanged artifacts reproduces the bytes.

Run it from the repository root after `ufem run all`:

    .venv/Scripts/python report/figures_src/make_figures.py
"""

